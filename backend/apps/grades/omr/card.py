def answer_cells():
    """답란 100칸 — `((문항번호, 선택지), (u, v))` 목록. 문항·선택지는 1부터."""
    us = [_u(x) + CALIBRATION_U for x in ANSWER_CHOICE_X]
    vs = [v + CALIBRATION_V for v in _even_rows(ANSWER_ROW_Y, ANSWER_QUESTIONS)]
    return [
        ((question, choice), (us[choice - 1], vs[question - 1]))
        for question in range(1, ANSWER_QUESTIONS + 1)
        for choice in range(1, ANSWER_CHOICES + 1)
    ]


def name_cells():
    """성명란 188칸 — `((열, 행), (u, v))` 목록. 열 1~12, 행 1~19. 열·행은 1부터.

    중성 열(2·5·8·11)만 15~19행이 있다. 실물 평균판 실측값이라 보정량을 더하지
    않는다 — 모듈 docstring "값의 출처" 참조.
    """
    vs = [_v_avg(y) for y in _even_span(NAME_ROW_Y, NAME_ROWS)]
    return [
        ((column, row), (_u_avg(NAME_COL_X[column - 1]), vs[row - 1]))
        for column in range(1, len(NAME_COL_X) + 1)
        for row in range(
            1, (NAME_ROWS if column in NAME_VOWEL_COLUMNS else NAME_CONSONANT_ROWS) + 1
        )
    ]


def phone_cells():
    """전화번호 40칸 — `((자리, 숫자), (u, v))` 목록. 자리 1~4, 숫자 0~9."""
    vs = [_v_avg(y) for y in _even_span(PHONE_ROW_Y, PHONE_DIGITS)]
    return [
        ((position, digit), (_u_avg(PHONE_COL_X[position - 1]), vs[digit]))
        for position in range(1, PHONE_POSITIONS + 1)
        for digit in range(PHONE_DIGITS)
    ]


def survey_number_cells():
    """조사 카드 수험번호 50칸 — `((자리, 숫자), (u, v))`. 자리 1~5, 숫자 0~9."""
    vs = [_v_avg(y) for y in _even_span(SURVEY_NUMBER_Y, PHONE_DIGITS)]
    return [
        ((position, digit), (_u_avg(SURVEY_NUMBER_X[position - 1]), vs[digit]))
        for position in range(1, SURVEY_NUMBER_POSITIONS + 1)
        for digit in range(PHONE_DIGITS)
    ]


def survey_score_cells():
    """조사 카드 점수 15칸 — `((자리, 숫자), (u, v))`. 자리는 `십`·`일`.

    숫자를 행번호가 아니라 **그 칸이 뜻하는 값**으로 적는다 — 1의 자리는 지면
    순서가 1,2,…,9,0 이라 행번호를 그대로 쓰면 마지막 칸이 10이 된다.
    """
    u = _u_avg(SURVEY_SCORE_X)
    cells = []
    for place, span, digits in (
        ("십", SURVEY_TENS_Y, SURVEY_TENS_DIGITS),
        ("일", SURVEY_ONES_Y, SURVEY_ONES_DIGITS),
    ):
        for digit, y in zip(digits, _even_span(span, len(digits))):
            cells.append(((place, digit), (u, _v_avg(y))))
    return cells


# --- 내부 부품 --------------------------------------------------------------


def _u(x):
    """빈 카드 픽셀 x → 정규좌표 u."""
    left, right = BLANK_MARK_X
    return (x - left) / (right - left)


def _v(y):
    """빈 카드 픽셀 y → 정규좌표 v."""
    top, bottom = BLANK_MARK_Y
    return (y - top) / (bottom - top)


def _even_rows(span, count):
    """첫 행·끝 행 중심 사이를 균등 분할한 정규좌표 목록.

    행마다 중심을 다 적지 않는 이유는 잰 값이 등간격이었기 때문이다 — 스무 개를
    적어 두면 그중 하나가 틀려도 눈에 안 띈다.
    """
    return [_v(y) for y in _even_span(span, count)]


def _u_avg(x):
    """평균판 픽셀 x → 정규좌표 u. 평균판은 마커 사각형을 2223.5px 로 편 렌더라
    원점 이동 없이 폭으로 나누기만 한다."""
    return x / 2223.5


def _v_avg(y):
    """평균판 픽셀 y → 정규좌표 v. 높이는 1493.5px."""
    return y / 1493.5


def _even_span(span, count):
    """첫 중심과 끝 중심 사이를 균등 분할한 픽셀 목록."""
    first, last = span
    step = (last - first) / (count - 1)
    return [first + step * index for index in range(count)]
