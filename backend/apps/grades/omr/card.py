"""판형 — 카드 위 셀이 어디에 있나. **이미지를 모른다. 순수 데이터다**(PRD 3.1.1).

판형이 바뀌면 **이 파일만** 갈아 끼운다. 읽는 코드(read)도 해석하는 코드(decode)도
그대로다. 카드는 앞으로 통일된다(decisions.md §5)므로 판형별 분기는 두지 않는다 —
한 벌만 두고 값을 바꾼다.

## 값의 출처

답란은 빈 카드 실물(`local/sources/basis/omr/test-omr-blank.pdf`)을 200dpi 로 렌더한
2339x1654 이미지에서 잰 픽셀 좌표다(2026-08-04). 성명·전화번호는 빈 카드가 아니라
**실물 스캔 65장을 마커 정규좌표로 정합해 평균 낸 판**(마커 사각형을 2223.5x1493.5px
로 편 렌더)에서 인쇄 링을 검출해 잰 좌표다(2026-08-05) — 실물 기준이므로 보정량이
없다. 어느 쪽이든 **재 온 단위 그대로 적고 정규화는 코드가 한다** — 손으로 환산해
적으면 열두 개 중 하나가 틀려도 아무도 못 찾는다.

정규좌표는 `normalize.CardFrame` 과 같은 축이다: (0,0) 카드 좌상 마커, (1,1) 우하
마커. 카드 위 자리를 "마커 간격의 몇 분의 몇"으로 적으면 스캔의 배율·기울기·
사다리꼴이 전부 변환에 흡수된다.

## 검산

버블 총수 328 = 성명 188 + 전화 40 + 답란 100. 빈 카드에서 링을 세었을 때
정확히 이 수가 나왔다. 값이 어긋나면 이 수부터 깨지므로 테스트가 먼저 잡는다.
"""

# --- 실측 기준 프레임 (빈 카드 200dpi 렌더의 마커 중심) ---------------------
BLANK_MARK_X = (56.5, 2280.0)
BLANK_MARK_Y = (88.5, 1582.0)

# --- 답란: 20문항 × 5지선다 -------------------------------------------------
#: 선택지 ①~⑤ 의 열 중심 x. 간격이 41px 로 균일하지만 잰 값을 그대로 둔다.
ANSWER_CHOICE_X = (1214.0, 1255.0, 1296.0, 1337.0, 1378.0)
#: 1번 행과 20번 행의 중심 y. 사이는 균등 분할(실측 행간격 65px).
ANSWER_ROW_Y = (241.0, 1467.0)
ANSWER_QUESTIONS = 20
ANSWER_CHOICES = 5

#: 실물 스캔 65장으로 맞춘 보정량(정규좌표). 빈 카드 PDF 값을 그대로 쓰면 셀 중심이
#: 버블 링 위에 걸친다 — 빈 카드가 다른 회차(`OMEGA black 3회`)라 배치가 미세하게 다르다.
#:
#: V 는 2026-08-05 재측정값이다. 6500칸 각각에서 **인쇄된 버블 테두리를 직접 찾아**
#: (스타디움 링 상관) 예측 중심과의 편차를 쟀더니 y 로 중앙값 +1.28px(200dpi) 남아
#: 있었다 — 평균판 잉크 최대화로 맞춘 옛값(-0.00143)의 잔차다. 그 치우침이 빈 줄의
#: 아래 링을 표본에 물려 **답 안 한 문항 3건이 ⑤ 로 읽혔다**(017-Q17·025-Q19·055-Q17).
#: U 잔차는 중앙값 -0.08px 로 측정 한계 밑이라 그대로 둔다.
CALIBRATION_U = 0.00220
CALIBRATION_V = -0.00057

#: 표본 반경(정규좌표, u·v 순). read 는 이 반경의 65% 안쪽만 표본한다.
#:
#: 답란 버블은 폭 18.3 x 높이 33.2px(200dpi)의 **세로로 긴 스타디움**이다 —
#: 65장에서 인쇄 테두리를 직접 재고, 빈 카드 렌더에서도 같은 값을 확인했다.
#: (한때 "빈 카드는 29x32 라 회차가 다르다"고 적었던 것은 **회차 차이가 아니라
#: 오측**이었다 — 링과 안쪽 글리프를 한 덩어리로 채워 bbox 를 잰 값이다.
#: 도판은 두 회차가 같고, 회차마다 움직이는 것은 **모양이 아니라 배치**다.)
#:
#: 옛값 14.5 는 65% 표본점(±9.4px)이 테두리 안쪽 여백(±7.9px)을 넘어 **오프셋 0
#: 에서 이미 링 위에 얹히는** 값이었고, 그래서 격자가 1px 만 밀려도 판정이
#: 뒤집혔다(여유가 음수였다).
#:
#: x 를 실측 반폭 9.15 가 아니라 11.0 으로 두는 이유: 65% 표본폭 7.15px 는 링 안
#: (여백 7.9px)에 머물면서도, 칸 옆으로 삐져나가게 칠한 마킹(65장 중 2건)을 놓치지
#: 않는 가장 넓은 자리다. 9.15 로 좁히면 그 2건이 빈칸으로 죽는다.
#: y 는 실측 반높이 16.6 그대로다(65% 표본높이 10.8px, 여백 15.4px).
ANSWER_BUBBLE_RADIUS = (11.0 / 2223.5, 16.6 / 1493.5)

# --- 성명란: 4글자 × (초성·중성·종성) 12열 ----------------------------------
#: 12열의 중심 x(평균판 px). 글자 사이 간격이 132.8~139.9px 로 **균일하지
#: 않아** 균등 분할하지 않고 열마다 그대로 적는다. 열 내 실측 산포는 0.33px 이하.
NAME_COL_X = (87.4, 128.5, 171.1, 220.2, 261.3, 303.9,
              355.9, 397.1, 439.6, 495.8, 536.9, 579.4)
#: 중성(모음) 열 — 1~19행(ㅏ~ㅢ)을 다 쓴다. 나머지 여덟 열(초·종성)은
#: 1~14행(ㄱ~ㅎ)까지만 있다. 8x14 + 4x19 = 188.
NAME_VOWEL_COLUMNS = (2, 5, 8, 11)
#: 1행과 19행의 중심 y(평균판 px). 사이는 균등 분할 — 실측 행간격 38.75px,
#: 균등 모형 잔차 최대 0.43px. 모음 15~19행도 같은 격자 위에 있다(어긋난
#: 반 행 자리는 링 겹침이 만든 유령 행이다 — 검출 문턱을 낮추면 거기 걸린다).
NAME_ROW_Y = (694.0, 1391.5)
NAME_ROWS = 19
NAME_CONSONANT_ROWS = 14
#: 성명 버블은 지름 ~31px 정원(스타디움이 아니다). 표본 반경(정규좌표, u·v 순) —
#: read 의 65% 표본폭 ±10.1px 는 테두리 안 여백(±13px) 안에 머문다.
NAME_BUBBLE_RADIUS = (15.5 / 2223.5, 15.5 / 1493.5)

# --- 전화번호 끝 4자리: 4열 × 숫자 0~9 --------------------------------------
#: 자리(왼→오른쪽) 4열의 중심 x(평균판 px). 열 간격 52.9 / 79.2 / 57.2px —
#: 가운데 구분선 때문에 **균일하지 않다.** 균등 분할로 적었다면 최대 13px 어긋났다.
PHONE_COL_X = (706.9, 759.8, 839.0, 896.1)
#: 숫자 0 행과 9 행의 중심 y(평균판 px). 균등 분할 — 실측 행간격 50.05px,
#: 잔차 최대 0.26px.
PHONE_ROW_Y = (698.7, 1149.2)
PHONE_POSITIONS = 4
PHONE_DIGITS = 10
#: 전화 버블은 답란과 같은 스타디움 인쇄물이라 표본 반경도 같은 것을 쓴다.
PHONE_BUBBLE_RADIUS = ANSWER_BUBBLE_RADIUS


def answer_cells():
    """답란 100칸 — `((문항번호, 선택지), (u, v))` 목록. 문항·선택지는 1부터."""
    us = [_u(x) + CALIBRATION_U for x in ANSWER_CHOICE_X]
    vs = [v + CALIBRATION_V for v in _even_rows(ANSWER_ROW_Y, ANSWER_QUESTIONS)]
    return [
        ((question, choice), (us[choice - 1], vs[question - 1]))
        for question in range(1, ANSWER_QUESTIONS + 1)
        for choice in range(1, ANSWER_CHOICES + 1)
    ]


def name_cells():
    """성명란 188칸 — `((열, 행), (u, v))` 목록. 열 1~12, 행 1~19. 열·행은 1부터.

    중성 열(2·5·8·11)만 15~19행이 있다. 실물 평균판 실측값이라 보정량을 더하지
    않는다 — 모듈 docstring "값의 출처" 참조.
    """
    vs = [_v_avg(y) for y in _even_span(NAME_ROW_Y, NAME_ROWS)]
    return [
        ((column, row), (_u_avg(NAME_COL_X[column - 1]), vs[row - 1]))
        for column in range(1, len(NAME_COL_X) + 1)
        for row in range(
            1, (NAME_ROWS if column in NAME_VOWEL_COLUMNS else NAME_CONSONANT_ROWS) + 1
        )
    ]


def phone_cells():
    """전화번호 40칸 — `((자리, 숫자), (u, v))` 목록. 자리 1~4, 숫자 0~9."""
    vs = [_v_avg(y) for y in _even_span(PHONE_ROW_Y, PHONE_DIGITS)]
    return [
        ((position, digit), (_u_avg(PHONE_COL_X[position - 1]), vs[digit]))
        for position in range(1, PHONE_POSITIONS + 1)
        for digit in range(PHONE_DIGITS)
    ]


# --- 내부 부품 --------------------------------------------------------------


def _u(x):
    """빈 카드 픽셀 x → 정규좌표 u."""
    left, right = BLANK_MARK_X
    return (x - left) / (right - left)


def _v(y):
    """빈 카드 픽셀 y → 정규좌표 v."""
    top, bottom = BLANK_MARK_Y
    return (y - top) / (bottom - top)


def _even_rows(span, count):
    """첫 행·끝 행 중심 사이를 균등 분할한 정규좌표 목록.

    행마다 중심을 다 적지 않는 이유는 잰 값이 등간격이었기 때문이다 — 스무 개를
    적어 두면 그중 하나가 틀려도 눈에 안 띈다.
    """
    return [_v(y) for y in _even_span(span, count)]


def _u_avg(x):
    """평균판 픽셀 x → 정규좌표 u. 평균판은 마커 사각형을 2223.5px 로 편 렌더라
    원점 이동 없이 폭으로 나누기만 한다."""
    return x / 2223.5


def _v_avg(y):
    """평균판 픽셀 y → 정규좌표 v. 높이는 1493.5px."""
    return y / 1493.5


def _even_span(span, count):
    """첫 중심과 끝 중심 사이를 균등 분할한 픽셀 목록."""
    first, last = span
    step = (last - first) / (count - 1)
    return [first + step * index for index in range(count)]
