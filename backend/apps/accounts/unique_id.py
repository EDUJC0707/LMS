"""원번(`students.unique_id`) 생성 규칙 — **유일한 준거** (2026-07-29 재개정).

원번은 관리자가 손으로 적어 넣는 값이 아니라 **(이름, 휴대폰)에서 계산되는
파생값**이다. 계정 일괄 발급(`provisioning.py`)·시드(`seed_demo`)가 이 모듈을
경유한다 — 규칙이 두 곳에 흩어지면 발급 경로마다 원번 체계가 갈린다
(`login_id.py` 와 같은 결).

## 규칙

| 대상 | 형식 | 예 |
|---|---|---|
| 원번 | `{정규화 이름}{휴대폰 뒷4자리}` | `김하늘0001` |

**학년은 원번에 들어가지 않는다.** 같은 날 오전에 넣었다가 걷어냈다 — 지면
전제가 바뀌면서(아래 OMR 절) 학년 자리가 설 자리가 없어졌다. `students.grade`
는 학생 정보로 계속 쓰지만 원번과는 무관하다. 그래서 **원번은 승급으로 바뀌지
않는다** — 사실상 불변이다(`promote_grade` 는 학년만 올린다).

## 원번 = 로그인 아이디에서 충돌 접미사를 뗀 값

로그인 아이디도 `{이름}{뒷4}`(8-4)이므로 둘은 **같은 몸통**이다. 충돌이 없으면
원번과 아이디가 글자 그대로 같고, 충돌이 있으면 아이디에만 한 글자 접미사가
붙는다(`김민준1234` / `김민준1234a` — `login_id.COLLISION_SUFFIXES`). 즉

    원번 == 로그인 아이디 - 접미사

이름 정규화·뒷4자리 추출은 `login_id.py` 함수를 그대로 재사용한다(무전화
학생이 학부모 번호 뒷4자리를 쓰는 8-3 규칙도 그 함수가 이미 가진다).

## 원번은 중복될 수 있다 — 그때는 사람이 고른다

동명이인 + 같은 뒷4자리면 **두 학생의 원번이 같다.** 이건 결함이 아니라 계약이다
(2026-07-29 사용자 확정). 아이디처럼 접미사로 해소하지 **않는** 이유:

지면(OMR 답안지·워크북)에 적히는 것은 이름과 뒷4자리뿐이다. 접미사는 지면에
나타날 수 없으므로, 원번에 접미사를 붙여 봐야 들어온 값과 대조되지 않는다 —
자동으로 갈라 놓아도 정작 갈라진 값이 지면에서 오지 않는다. 그래서 겹치는
원번은 매칭에서 **중복으로 떨어뜨리고 관리자가 고른다**(`grades.workbook_admin`
의 (원번, 이름) 대조, `answer_sheets.match_status = 중복`). 컬럼도 단독 UNIQUE
가 아니라 인덱스만 둔다(`models.Student.unique_id` 계약).

## 지면에 들어오는 것이 곧 원번이다 (OMR·워크북)

**OMR 마킹이 아니라 손글씨 전제다**(2026-07-29 사용자 확정 — "OMR은 이름
뒷자리만 들어올 것 같아"). 답안지·워크북에는 **이름 + 뒷4자리**가 적혀 들어오고,
그게 그대로 원번이다. 따라서 지면 값과 저장된 원번을 **전체 비교**하는 것이
맞다 — 숫자부만 뽑아 비교하던 5자리 마킹 전제(같은 날 오전 판의 `numeric_key`)
는 소멸했다. PRD 8-9 의 "착수 전 numeric_key 로 바꿔야 한다"는 경고도 함께 정정됐다.

## 순수성

전 함수가 순수하다. DB 도 `is_taken` 같은 술어도 필요 없다 — 원번은 충돌을
해소하지 않으므로 "이미 쓰는 값인가"를 물을 이유가 없다. 실패 사유는 전부
이름·번호에서 오므로 예외도 `LoginIdError` 하나를 그대로 쓴다.
"""
from .login_id import normalize_name, student_phone_tail4


def build_unique_id(name, phone, parent_phone="") -> str:
    """원번 = 정규화 이름 + 휴대폰 뒷4자리(무전화면 학부모 번호)."""
    tail = student_phone_tail4(phone, parent_phone)  # 번호 판정이 이름 정규화보다 먼저
    return f"{normalize_name(name)}{tail}"
