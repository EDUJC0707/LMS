"""대조키(`students.matching_key`) 생성 규칙 — **유일한 준거** (2026-08-05 재개정).

## 원번과 대조키는 다른 것이다

| | 무엇 | 유일한가 | 어디 있나 |
|---|---|---|---|
| **원번** | 학생의 번호. 로그인 아이디와 같은 값 | **예** | `users.login_id` |
| **대조키** | 지면 대조 전용 키 | **아니오** | `students.matching_key` |

2026-08-05 확정: **원번은 `login_id` 하나로 통합됐다.** 예전에는 원번을 따로
저장했는데, 충돌 접미사(`a`·`b`…)만 빼면 로그인 아이디와 글자까지 같은 값이라
같은 것이 두 이름으로 존재했다. 컬럼 이름(`unique_id`)이 "유일하다"고 말하면서
계약은 "중복될 수 있다"였던 것도 그 혼선의 산물이다.

남은 컬럼은 **지면 대조라는 한 가지 일**만 한다. 그래서 이름도 그 일로 바꿨다.

## 규칙

    대조키 = {정규화 이름}{휴대폰 뒷4자리}     예: 김하늘0001

로그인 아이디에서 충돌 접미사를 뗀 값과 같다. 이름 정규화·뒷4자리 추출은
`login_id.py` 함수를 그대로 재사용한다(무전화 학생이 학부모 번호 뒷4자리를
쓰는 8-3 규칙도 그 함수가 이미 가진다). 관리자가 손으로 적어 넣는 값이 아니라
**(이름, 휴대폰)에서 계산되는 파생값**이고, 계정 일괄 발급(`provisioning.py`)과
시드(`seed_demo`)가 전부 이 모듈을 경유한다 — 규칙이 흩어지면 발급 경로마다
체계가 갈린다.

**학년은 들어가지 않는다** — 지면에 학년이 나타나지 않기 때문이다. 그래서
승급해도 대조키는 바뀌지 않는다(`promote_grade` 는 학년만 올린다).

## 왜 접미사를 안 붙이나 — 지면이 접미사를 못 담는다

지면에 오는 것은 이름과 뒷4자리뿐이다.

- **OMR 답안지**: 학생이 자모 격자와 숫자 격자에 마킹한다. 격자에 접미사를
  찍을 칸이 아예 없다
- **워크북**: 조교가 손으로 적는데, 여기서도 **대조키만 적는다**(2026-08-05 확정)

그러니 대조키에 접미사를 붙여 봐야 들어온 값과 대조되지 않는다 — 자동으로
갈라 놓아도 정작 갈라진 값이 지면에서 오지 않는다. 동명이인 + 같은 뒷4자리면
**두 학생의 대조키가 같고, 그건 결함이 아니라 계약이다.** 겹치면 매칭에서
중복으로 떨어뜨리고 **관리자가 고른다**(`grades.workbook_admin` 의 (대조키,
이름) 대조, `answer_sheets.match_status = 중복`). 컬럼도 단독 UNIQUE 가 아니라
인덱스만 둔다(`models.Student.matching_key` 계약).

지면 값과 저장된 대조키는 **전체 비교**한다 — 숫자부만 뽑아 비교하던 옛 5자리
마킹 전제(`numeric_key`)는 2026-07-29 에 소멸했다.

## 순수성

전 함수가 순수하다. DB 도 필요 없다 — 대조키는 충돌을 해소하지 않으므로
"이미 쓰는 값인가"를 물을 이유가 없다. 실패 사유는 전부 이름·번호에서 오므로
예외도 `LoginIdError` 하나를 그대로 쓴다.
"""
from .login_id import normalize_name, student_phone_tail4


def build_matching_key(name, phone, parent_phone="") -> str:
    """대조키 = 정규화 이름 + 휴대폰 뒷4자리(무전화면 학부모 번호)."""
    tail = student_phone_tail4(phone, parent_phone)  # 번호 판정이 이름 정규화보다 먼저
    return f"{normalize_name(name)}{tail}"
